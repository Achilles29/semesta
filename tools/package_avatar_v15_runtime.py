"""Publish self-contained GLBs plus glTFs sharing content-addressed textures.

Only repacks binary ranges. Geometry, morphs, animation and image bytes are exact.
"""
import json,struct,hashlib,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'ilustrasi/avatar-v2/farmer-v15-proportions'
out=ROOT/'public/models/characters/v15';runtime=out/'runtime';runtime.mkdir(parents=True,exist_ok=True)
catalog=json.loads((ROOT/'game-src/avatar-v15-catalog.json').read_text(encoding='utf-8'));manifest={};total=0
def publish(data,suffix):
    name=hashlib.sha256(data).hexdigest()[:24]+suffix;(runtime/name).write_bytes(data);return name
for profile in catalog['profiles']:
    profile_id=profile['id'];raw=(source/profile_id/'avatar.glb').read_bytes();size=struct.unpack_from('<I',raw,12)[0];doc=json.loads(raw[20:20+size]);binary=raw[28+size:];total+=len(raw)
    views=doc['bufferViews'];images=set()
    for image in doc['images']:
        index=image.pop('bufferView');images.add(index);view=views[index];start=view.get('byteOffset',0);data=binary[start:start+view['byteLength']]
        suffix='.png' if image.get('mimeType')=='image/png' else '.jpg';image['uri']=publish(data,suffix)
    packed=bytearray();remap={};newviews=[]
    for i,view in enumerate(views):
        if i in images:continue
        packed.extend(b'\0'*((-len(packed))%4));start=view.get('byteOffset',0);new=dict(view,byteOffset=len(packed));packed.extend(binary[start:start+view['byteLength']]);remap[i]=len(newviews);newviews.append(new)
    def rewrite(value):
        if isinstance(value,dict):
            for key,item in value.items():
                if key=='bufferView':value[key]=remap[item]
                else:rewrite(item)
        elif isinstance(value,list):
            for item in value:rewrite(item)
    rewrite(doc);doc['bufferViews']=newviews;doc['buffers']=[{'byteLength':len(packed),'uri':publish(bytes(packed),'.bin')}]
    data=json.dumps(doc,separators=(',',':')).encode();name=publish(data,'.gltf');manifest[profile_id]=name
    shutil.copyfile(source/profile_id/'avatar.glb',out/(profile_id+'.glb'))
(runtime/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',newline='\n')
# The JS manifest is bundled, so each deployment references its matching assets.
(ROOT/'game-src/avatar-v15-runtime-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
used=set(manifest.values())
for name in manifest.values():
    d=json.loads((runtime/name).read_text());used.update(i['uri'] for i in d['images']);used.add(d['buffers'][0]['uri'])
# Keep previous local cache files usable, but commit only this release's hashes.
(runtime/'.gitignore').write_text('# Generated by package_avatar_v15_runtime.py\n*.bin\n*.gltf\n*.png\n*.jpg\n'+''.join('!'+name+'\n' for name in sorted(used)),newline='\n')
report={'profiles':len(manifest),'glbBytes':total,'sharedRuntimeBytes':sum((runtime/name).stat().st_size for name in used),'files':len(used)}
(source/'runtime-package.json').write_text(json.dumps(report,indent=2));print(json.dumps(report))
